// Copies the app's own artwork into public/app (read-only use of ../frontend).
import { cpSync, mkdirSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "../frontend/src/assets");
const dest = join(root, "public/app");
mkdirSync(dest, { recursive: true });
for (const f of readdirSync(src).filter((f) => f.endsWith(".png"))) cpSync(join(src, f), join(dest, f));
console.log("synced", readdirSync(dest).length, "assets");

// Design tokens: pull @theme, :root and @utility blocks verbatim from the app's styles.css
// (skipping its page-level html/body rules, which would fight the video canvas).
import { readFileSync, writeFileSync } from "node:fs";
const css = readFileSync(join(root, "../frontend/src/styles.css"), "utf8");
const blocks = [];
for (let i = 0; i < css.length; i++) {
  const rest = css.slice(i);
  const head = rest.match(/^(@theme inline|:root|@utility [\w-]+)\s*\{/);
  if (!head || (i > 0 && css[i - 1] !== "\n")) continue;
  let depth = 0;
  let j = i;
  for (; j < css.length; j++) {
    if (css[j] === "{") depth++;
    if (css[j] === "}" && --depth === 0) break;
  }
  blocks.push(css.slice(i, j + 1));
  i = j;
}
writeFileSync(
  join(root, "src/app-tokens.css"),
  `/* Generated by scripts/sync-assets.mjs from frontend/src/styles.css. Do not edit. */\n\n${blocks.join("\n\n")}\n`,
);
console.log("synced", blocks.length, "token blocks");
