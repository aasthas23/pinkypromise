#!/usr/bin/env python3
"""
Builds the real robocall clips bundled with Scam Coach.

Source: Robocall Audio Dataset (Prasad & Reaves, NC State, TR-2023-1),
https://github.com/wspr-ncsu/robocall-audio-dataset. The recordings come from
the FTC's Project Point of No Entry and are in the public domain.

Safety rule: a clip is only bundled if its transcript contains no phone number
or callback instruction, so the app never plays a number a scammer may still
answer. Whisper transcripts can miss speech, so a person should still listen to
every clip before a demo (see assets/robocalls/SOURCES.md).

Usage (needs ffmpeg/ffprobe on PATH):
    python3 -I scripts/robocalls/build_clips.py --cache /path/to/empty/cache/dir
Downloads land in the cache dir. Outputs:
    assets/robocalls/<id>.m4a
    src/features/simulator/recordings/catalog.ts   (generated, do not edit)
"""
import argparse
import csv
import json
import re
import subprocess
import sys
import urllib.parse
import urllib.request
from pathlib import Path

REPO = 'https://raw.githubusercontent.com/wspr-ncsu/robocall-audio-dataset/main/'
FRONTEND = Path(__file__).resolve().parents[2]
ASSET_DIR = FRONTEND / 'assets' / 'robocalls'
CATALOG = FRONTEND / 'src' / 'features' / 'simulator' / 'recordings' / 'catalog.ts'

# id -> (pool, dataset file stem). Picked by hand: complete openers, no callback
# numbers, and audio length consistent with the transcript.
CLIPS = {
    'amz-1112259': ('amazon_order', '1112259'),
    'amz-daniel': ('amazon_order', '1638881759.18243_in_Family_Communication_Robocall__Amazon-SuspiciousCharge'),
    'amz-1211775': ('amazon_order', '1211775'),
    'amz-795470': ('amazon_order', '795470'),
    'amz-668376': ('amazon_order', '668376'),
    'ssa-638881': ('ssa_suspension', '638881'),
    'ssa-509601': ('ssa_suspension', '509601'),
    'ssa-241125': ('ssa_suspension', '241125'),
    'ssa-576026': ('ssa_suspension', '576026'),
}

NUM_WORD = r'(zero|oh|one|two|three|four|five|six|seven|eight|nine)'
UNSAFE = [
    r'\d{3}[\s.-]*\d{3,4}',      # 555-0100 style
    r'\d{7,}',                   # long digit runs
    r'\(\d{3}\)',                # area codes
    rf'({NUM_WORD}[\s,.-]+){{3,}}',  # spelled-out digit runs
    r'call (us )?(back )?(at|on)\b',
    r'toll[- ]free',
    r'\bdial\b',
    r'https?://|www\.|\.com\b',
]


def unsafe_reason(transcript: str):
    for pat in UNSAFE:
        m = re.search(pat, transcript, re.I)
        if m:
            return f'matches {pat!r}: {m.group(0)!r}'
    return None


def run(*cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--cache', required=True, type=Path)
    args = ap.parse_args()
    args.cache.mkdir(parents=True, exist_ok=True)

    meta_path = args.cache / 'metadata.csv'
    if not meta_path.exists():
        urllib.request.urlretrieve(REPO + 'metadata.csv', meta_path)
    rows = {}
    with open(meta_path, encoding='utf-8') as f:
        for r in csv.DictReader(f):
            rows[Path(r['file_name']).name.removesuffix('_normalized.wav')] = r

    ASSET_DIR.mkdir(parents=True, exist_ok=True)
    entries = []
    for clip_id, (pool, stem) in CLIPS.items():
        row = rows[stem]
        transcript = ' '.join(row['transcript'].split())
        reason = unsafe_reason(transcript)
        if reason:
            sys.exit(f'{clip_id}: refusing to bundle, transcript {reason}')

        src = args.cache / Path(row['file_name']).name
        if not src.exists():
            urllib.request.urlretrieve(REPO + urllib.parse.quote(row['file_name']), src)

        out = ASSET_DIR / f'{clip_id}.m4a'
        # Trim leading/trailing silence, normalize loudness, keep phone bandwidth.
        run('ffmpeg', '-y', '-hide_banner', '-loglevel', 'error', '-i', str(src),
            '-af', 'silenceremove=start_periods=1:start_threshold=-40dB:start_silence=0.2,'
                   'areverse,silenceremove=start_periods=1:start_threshold=-40dB:start_silence=0.4,areverse,'
                   'highpass=f=250,lowpass=f=3600,loudnorm=I=-18:TP=-2',
            '-ac', '1', '-ar', '16000', '-c:a', 'aac', '-b:a', '32k', str(out))
        duration = float(run('ffprobe', '-v', 'error', '-show_entries', 'format=duration',
                             '-of', 'csv=p=0', str(out)).strip())
        entries.append({
            'id': clip_id,
            'pool': pool,
            'transcript': transcript,
            'durationSec': round(duration, 1),
            'datasetFile': row['file_name'],
            'ftcLetter': row['case_pdf'],
        })
        print(f'{clip_id:12} {duration:5.1f}s  {out.stat().st_size // 1024} KB')

    lines = [
        '// GENERATED by scripts/robocalls/build_clips.py. Do not edit by hand.',
        '// Real robocall recordings from the FTC Project Point of No Entry (public domain),',
        '// via the Robocall Audio Dataset (Prasad & Reaves, NC State, TR-2023-1).',
        "import type { RecordingClip } from '../types';",
        '',
        'export const recordingClips: RecordingClip[] = [',
    ]
    for e in entries:
        lines += [
            '  {',
            f"    id: {json.dumps(e['id'])},",
            f"    pool: {json.dumps(e['pool'])},",
            f"    transcript: {json.dumps(e['transcript'], ensure_ascii=False)},",
            f"    durationSec: {e['durationSec']},",
            f"    datasetFile: {json.dumps(e['datasetFile'])},",
            f"    ftcLetter: {json.dumps(e['ftcLetter'])},",
            f"    source: require('../../../../assets/robocalls/{e['id']}.m4a'),",
            '  },',
        ]
    lines += ['];', '']
    CATALOG.parent.mkdir(parents=True, exist_ok=True)
    CATALOG.write_text('\n'.join(lines), encoding='utf-8')
    print(f'wrote {CATALOG.relative_to(FRONTEND)}')


if __name__ == '__main__':
    main()
